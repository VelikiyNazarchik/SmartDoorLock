LATIN_LOOKALIKE = {
    'А': 'A', 'В': 'B', 'Е': 'E', 'К': 'K', 'М': 'M', 'Н': 'H', 'О': 'O', 'Р': 'P',
    'С': 'C', 'Т': 'T', 'Х': 'X', 'І': 'I',
}


def art_to_columns(rows):
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), rows
    cols = []
    for x in range(5):
        v = 0
        for y in range(7):
            if rows[y][x] == '#':
                v |= 1 << y
        cols.append(v)
    return tuple(cols)


def main():
    cyr_names = list(CYRILLIC_ART.keys())
    cyr_glyphs = [art_to_columns(CYRILLIC_ART[c]) for c in cyr_names]

    # Glyph ids: 0..94 = ASCII 0x20..0x7E, 95.. = Cyrillic extras
    def glyph_id(ch):
        if ch in LATIN_LOOKALIKE:
            return ord(LATIN_LOOKALIKE[ch]) - 0x20
        return 95 + cyr_names.index(ch)

    upper = [chr(c) for c in range(0x410, 0x430)]           # А..Я
    upper_map = [glyph_id(ch) for ch in upper]
    extra = {0x404: 'Є', 0x406: 'І', 0x407: 'Ї', 0x490: 'Ґ'}

    out = []
    out.append("/* Generated by Tools/fontgen.py - do not edit by hand. */")
    out.append('#include "font5x7.h"')
    out.append("")
    out.append("static const uint8_t font_glyphs[][FONT5X7_W] = {")
    for i, g in enumerate(ASCII):
        ch = chr(0x20 + i)
        label = {'\\': 'backslash', '/': 'slash'}.get(ch, ch)
        out.append("    { %s },  /* '%s' */" % (", ".join("0x%02X" % b for b in g), label))
    for name, g in zip(cyr_names, cyr_glyphs):
        out.append("    { %s },  /* U+%04X */" % (", ".join("0x%02X" % b for b in g), ord(name)))
    out.append("};")
    out.append("")
    out.append("/* U+0410..U+042F -> glyph index */")
    out.append("static const uint8_t cyr_upper[32] = {")
    out.append("    " + ", ".join(str(v) for v in upper_map))
    out.append("};")
    out.append("")
    out.append("#define GLYPH_QUESTION ('?' - 0x20)")
    out.append("")
    out.append("static uint8_t glyph_index(uint32_t cp)")
    out.append("{")
    out.append("    if (cp >= 0x20U && cp <= 0x7EU) {")
    out.append("        return (uint8_t)(cp - 0x20U);")
    out.append("    }")
    out.append("    if (cp >= 0x430U && cp <= 0x44FU) {")
    out.append("        cp -= 0x20U;   /* lower-case Cyrillic is drawn as capitals */")
    out.append("    } else if (cp == 0x454U || cp == 0x456U || cp == 0x457U) {")
    out.append("        cp -= 0x50U;")
    out.append("    } else if (cp == 0x491U) {")
    out.append("        cp = 0x490U;")
    out.append("    } else if (cp == 0x2019U) {")
    out.append("        return (uint8_t)('\\'' - 0x20);")
    out.append("    }")
    out.append("    if (cp >= 0x410U && cp <= 0x42FU) {")
    out.append("        return cyr_upper[cp - 0x410U];")
    out.append("    }")
    out.append("    switch (cp) {")
    for code, ch in sorted(extra.items()):
        out.append("    case 0x%04XU: return %d;" % (code, glyph_id(ch)))
    out.append("    default: return GLYPH_QUESTION;")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("const uint8_t *FONT5X7_Glyph(uint32_t codepoint)")
    out.append("{")
    out.append("    return font_glyphs[glyph_index(codepoint)];")
    out.append("}")
    out.append("")

    dst = Path(__file__).resolve().parent.parent / "Drivers" / "BSP" / "gfx" / "font5x7.c"
    dst.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print("wrote", dst, "glyphs:", len(ASCII) + len(cyr_glyphs))


if __name__ == "__main__":
    main()
